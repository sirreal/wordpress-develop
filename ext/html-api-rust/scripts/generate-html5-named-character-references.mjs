#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const entitiesPath = path.resolve(scriptDir, "../../../tests/phpunit/data/html5-entities/entities.json");
const outputPath = path.resolve(scriptDir, "../src/html5_named_character_references.rs");

const entities = JSON.parse(await readFile(entitiesPath, "utf8"));

function byteStringLiteral(value) {
	for (const byte of Buffer.from(value, "utf8")) {
		if (byte < 0x20 || byte > 0x7e) {
			throw new Error(`Expected ASCII entity name, got ${JSON.stringify(value)}`);
		}
	}

	return `b"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

function unicodeEscape(codePoint) {
	return `\\u{${codePoint.toString(16).toUpperCase()}}`;
}

function characterReferenceExpression(characters) {
	const codePoints = Array.from(characters, (character) => character.codePointAt(0));

	if (codePoints.length === 1) {
		return `CharacterReference::Scalar('${unicodeEscape(codePoints[0])}')`;
	}

	return `CharacterReference::Text("${codePoints.map(unicodeEscape).join("")}")`;
}

const entries = Object.entries(entities).map(([reference, { characters }]) => {
	if (!reference.startsWith("&")) {
		throw new Error(`Expected entity reference to start with &: ${reference}`);
	}

	return `    (${byteStringLiteral(reference.slice(1))}, ${characterReferenceExpression(characters)}),`;
});

const output = `// Generated by scripts/generate-html5-named-character-references.mjs from
// tests/phpunit/data/html5-entities/entities.json. Do not edit manually.

use super::CharacterReference;

pub(super) const NAMED_CHARACTER_REFERENCES: &[(&[u8], CharacterReference)] = &[
${entries.join("\n")}
];
`;

await writeFile(outputPath, output);
